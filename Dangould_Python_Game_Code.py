import random

# Assigns a numerical ranking to each difficulty to compare best games
difficulty_ranking ={'easy':1, 'medium':2, 'hard':3}

# Sets global variables to track player statistics across games
games_played = 0
games_won = 0
games_lost = 0
best_attempts = None
best_difficulty = None

# Display the game rules and how to play
def show_instructions():
    print('')
    print('        GUESS THE NUMBER        ')
    print('')
    print("I'm thinking of a number")
    print('Can you guess it?')
    print('')
    print('HOW TO PLAY')
    print('- Choose a difficulty')
    print('     Easy   - 7 attempts at range 1-50')
    print('     Medium - 6 attempts at range 1-100')
    print('     Hard   - 5 attempts at range 1-200')
    print("- I'll pick a random number within that difficulty's range.")
    print('- Enter your guesses one at a time.')
    print("- I'll tell you if your guess is too high or too low.")
    print('- You have a limited number of attempts.')
    print('- Guess the number before you run out of attempts to win!')
    print('')
    print('Good luck!')

# Display the player's statistics and best game
def show_stats():
  # Avoid division by zero before any games have been played
  if games_played == 0:
    win_rate = 0
  else:
    win_rate = round(games_won/games_played*100,1)

  print('')
  print('           YOUR STATS           ')
  print('')
  print('Games played:    {}'.format(games_played))
  print('Games Won:       {}'.format(games_won))
  print('Games Lost:      {}'.format(games_lost))
  print('Win Rate:        {}%'.format(win_rate))
  print('Best game:       {} guesses ({})'.format(best_attempts, best_difficulty))
  print('')

# Get the player's difficulty choice to set the game settings
def choose_difficulty():
  print('')
  print('       CHOOSE DIFFICULTY'        )
  print('')
  print('Easy')
  print('Medium')
  print('Hard')
  print('')

  difficulty = input('Choose a difficulty: ').lower()

  # Keep requesting input until a valid difficulty is entered
  while difficulty not in difficulty_ranking:
    difficulty = input('Please enter easy, medium or hard: ').lower()

    #Set the number range and maximum attempts for the chosen difficulty
  if difficulty == 'easy':
    limit = 50
    max_attempts = 7
  elif difficulty == 'medium':
    limit = 100
    max_attempts = 6
  elif difficulty == 'hard':
    limit = 200
    max_attempts = 5

  return difficulty, limit, max_attempts

# Run a round, process guesses, provide clues and update statistics
def play_game(difficulty, limit, max_attempts, target_number):
  attempts = 1
  guess = check_guess(limit)

  # Continue until the player guesses correctly or runs out of attempts
  while guess != target_number and attempts<max_attempts:
    if guess > target_number:
      print('')
      print('Too high!')
    else:
      print('')
      print('Too low!')
    attempts += 1
    print('You have {} attempts remaining.'.format(max_attempts - attempts + 1))
    print('')
    guess = check_guess(limit)

    # Provide an odd/even clue before the player's final attempt
    if attempts == max_attempts-1:
      if target_number % 2 == 0:
        number_type = 'even'
      else:
        number_type = 'odd'
      print('CLUE: The number is {}'.format(number_type))

  if guess == target_number:
    global games_won
    global games_lost
    global best_attempts
    global best_difficulty
    games_won += 1
    print('YOU WON!')
    print('You guessed the number in {} attempts.'.format(attempts))

    # Record the first win or a win achieved in fewer attempts as the best game
    if best_attempts is None:
      best_attempts = attempts
      best_difficulty = difficulty
    elif best_attempts > attempts:
      best_attempts = attempts
      best_difficulty = difficulty
    # If attempts are equal, favour the higher difficulty
    elif best_attempts == attempts:
      if difficulty_ranking[difficulty] > difficulty_ranking[best_difficulty]:
        best_difficulty = difficulty
  else:
    games_lost += 1
    print('GAME OVER!')
    print('You ran out of attempts.')
    print('The number was {}'.format(target_number))

# Validate the player's guess and return a valid integer
def check_guess(limit):
  user_guess = input('Guess a number: ')

  while True:
    # Convert the input to an integer, handling non-numeric input
    try:
      guess = int(user_guess)
    except:
      print('GUESS INVALID')
      print('Please enter a valid number.')
      print('')
      user_guess = input('Guess a number: ')
      print('')
      continue

    # Reject guesses outside the permitted range
    if guess not in range(1,limit+1):
      print('GUESS INVALID')
      print('Please enter a number between 1 and {}'.format(limit))
      print('')
      user_guess = input('Guess a number: ')
      print('')
      continue

    return guess

# Display the post-game menu and handle the player's choice
def game_menu():
  menu_options = ['y','n','s','i']

  print('')
  print('           GAME MENU           ')
  print('')
  print('[Y] Play Again')
  print('[S] See Stats')
  print('[I] Instructions')
  print('[N] Exit')
  print('')

  menu_choice = input('Choose an option: ').lower()

  # Keep requesting input until a valid menu option is entered
  while menu_choice not in menu_options:
    print('Please enter a valid option.')
    menu_choice = input('Choose an option: ').lower()

  if menu_choice == menu_options[0]:
    game()
  elif menu_choice == menu_options[1]:
    print('Thanks for playing!')
  elif menu_choice == menu_options[2]:
    show_stats()
    game_menu()
  elif menu_choice == menu_options[3]:
    show_instructions()
    game_menu()

#Set up a new game, run it and display the post-game menu.
def game():
  # Add to the total number of games started
  global games_played
  games_played += 1

  # Get the settings for the player's chosen difficulty
  difficulty, limit, max_attempts = choose_difficulty()

  # Generate a random target number within the selected range
  target_number = random.randint(1, limit)

  print('')
  print("I'm thinking of a number between 1 and {}.".format(limit))
  print('You have {} attempts.'.format(max_attempts))
  print('')

  # Run the game round, then display the post-game menu
  play_game(difficulty, limit, max_attempts, target_number)
  game_menu()

# Display the instructions and start the game
show_instructions()
game()

